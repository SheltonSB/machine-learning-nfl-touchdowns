def get_latest_team(player_id: str) -> str:
    """Return the most recent team for a player from game_logs."""
    try:
        db.connect()
        df = pd.read_sql_query(
            """
            SELECT gl.team
            FROM game_logs gl
            WHERE gl.player_id = ? AND gl.position = 'QB' AND gl.team IS NOT NULL
            ORDER BY gl.year DESC, gl.week DESC
            LIMIT 1
            """,
            db.conn,
            params=(player_id,)
        )
        db.disconnect()
        if not df.empty and isinstance(df.loc[0, 'team'], str) and df.loc[0, 'team'] != '':
            return df.loc[0, 'team']
        return 'Unknown'
    except Exception:
        return 'Unknown'

def get_qb_list():
    """Get list of QBs from database, including most recent team."""
    try:
        db.connect()
        qbs = pd.read_sql_query(
            """
            SELECT DISTINCT bs.player_id, bs.name AS name,
                   COALESCE(latest.team, '') AS team
            FROM basic_stats bs
            LEFT JOIN (
                SELECT gl.player_id, gl.team
                FROM game_logs gl
                JOIN (
                    SELECT player_id, MAX(year * 100 + week) AS max_yw
                    FROM game_logs
                    WHERE position = 'QB'
                    GROUP BY player_id
                ) m
                ON m.player_id = gl.player_id AND (gl.year * 100 + gl.week) = m.max_yw
                WHERE gl.position = 'QB'
            ) AS latest
            ON latest.player_id = bs.player_id
            JOIN game_logs gl_filter ON gl_filter.player_id = bs.player_id AND gl_filter.position = 'QB'
            WHERE bs.position = 'QB'
            ORDER BY bs.name
            """,
            db.conn
        )
        db.disconnect()
        
        # Debug: Check if we got the expected columns
        if qbs.empty:
            st.warning("No QB data found in database")
            return pd.DataFrame()
        
        # Ensure we have the required columns
        required_cols = ['player_id', 'name', 'team']
        missing_cols = [col for col in required_cols if col not in qbs.columns]
        if missing_cols:
            st.error(f"Missing columns in QB data: {missing_cols}")
            st.write("Available columns:", list(qbs.columns))
            return pd.DataFrame()
        
        return qbs
    except Exception as e:
        st.error(f"Error loading QB list: {e}")
        return pd.DataFrame()

def get_qb_recent_stats(player_id, num_games=3):
    """Get recent stats for a QB."""
    try:
        db.connect()
        stats = pd.read_sql_query("""
            SELECT 
                gl.year, gl.week, gl.team, gl.opponent,
                qs.passing_yards, qs.td_passes, qs.interceptions,
                qs.passes_attempted, qs.passes_completed,
                qs.completion_percentage, qs.yards_per_attempt, qs.passer_rating
            FROM game_logs gl
            JOIN qb_stats qs ON gl.id = qs.game_log_id
            WHERE gl.player_id = ? AND gl.position = 'QB'
            ORDER BY gl.year DESC, gl.week DESC
            LIMIT ?
        """, db.conn, params=(player_id, num_games))
        db.disconnect()
        return stats
    except Exception as e:
        st.error(f"Error loading QB stats: {e}")
        return pd.DataFrame()

def get_qb_basic_info(player_id):
    """Get basic info for a QB."""
    try:
        db.connect()
        info = pd.read_sql_query(
            """
            SELECT name AS name, age AS age, height AS height, weight AS weight, experience AS experience
            FROM basic_stats
            WHERE player_id = ?
            """,
            db.conn,
            params=(player_id,)
        )
        db.disconnect()
        return info.iloc[0] if len(info) > 0 else None
    except Exception as e:
        st.error(f"Error loading QB info: {e}")
        return None

def calculate_features(qb_info, recent_stats):
    """Calculate features for prediction."""
    if recent_stats.empty:
        return None
    
    # Calculate rolling averages (3-game rolling averages to match training data)
    avg_yards = recent_stats['passing_yards'].mean()
    avg_tds = recent_stats['td_passes'].mean()
    avg_attempts = recent_stats['passes_attempted'].mean()
    
    # Create feature vector in the exact order the model expects (7 features)
    # Order: Passing Yards_roll3, TD Passes_roll3, Passes Attempted_roll3, Age, Experience, Height, Weight
    features = [
        avg_yards,                    # Passing Yards_roll3
        avg_tds,                      # TD Passes_roll3
        avg_attempts,                 # Passes Attempted_roll3
        qb_info.get('age', 0),        # Age
        qb_info.get('experience', 0), # Experience
        qb_info.get('height', 0),     # Height (inches)
        qb_info.get('weight', 0)      # Weight (lbs)
    ]
    
    return features

